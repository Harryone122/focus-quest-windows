const {app,BrowserWindow}=require('electron')
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..'),out=path.join(root,'previews/cloud-whale-qa')
fs.mkdirSync(out,{recursive:true});app.setPath('userData',fs.mkdtempSync(path.join(os.tmpdir(),'focusquest-whale-proto-')))
;(async()=>{
 await app.whenReady();const win=new BrowserWindow({width:1500,height:940,show:true,webPreferences:{contextIsolation:true}})
 win.webContents.on('console-message',(_e,level,message)=>{if(level>=3)console.log('renderer:',message)})
 win.webContents.setBackgroundThrottling(false)
 await win.loadFile(path.join(root,'docs/prototypes/cloud-ruins.html'))
 const js=x=>win.webContents.executeJavaScript(x,true)
 for(let i=0;i<80&&!await js('!!window.__proto?.s');i++)await new Promise(r=>setTimeout(r,100))
 await js('window.__proto.scenario=4;window.__proto.start()')
 const clockStart=await js('window.__proto.s.debugState().sim')
 await new Promise(r=>setTimeout(r,3100))
 const clockEnd=await js('window.__proto.s.debugState().sim')
 console.log(JSON.stringify({clockStart,clockEnd,delta:clockEnd-clockStart,hold:await js("window.__hold"),paused:await js("window.__proto.s.debugState().paused"),visibility:await js("document.visibilityState")}));assert(clockEnd-clockStart>2.5&&clockEnd-clockStart<3.9,'Prototype clock must advance once per real second')
 await js('window.__hold=true;window.__proto.s.playStory("whale")')
 await new Promise(r=>setTimeout(r,900))
 const initial=await js('window.__proto.s.debugState().sim')
 await js('window.__proto.s.__advance(40);window.__proto.s.renderNow()')
 await new Promise(r=>setTimeout(r,3000))
 await js('window.__proto.s.renderNow()')
 await new Promise(r=>setTimeout(r,1200))
 const st=await js('window.__proto.s.debugState()')
 const png=(await win.webContents.capturePage()).toPNG();fs.writeFileSync(path.join(out,'prototype-midpass.png'),png)
 const report={clockAdvance:clockEnd-clockStart,initial,sim:st.sim,whale:st.story.whale,pngBytes:png.length}
 assert(st.story.whale>0.5);assert(png.length>50000,'Visible prototype capture expected')
 fs.writeFileSync(path.join(out,'prototype-report.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));app.exit(0)
})().catch(e=>{console.error(e);app.exit(1)})
