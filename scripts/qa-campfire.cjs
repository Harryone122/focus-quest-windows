// Isolated real-Electron smoke test of the production renderer and campfire prototype port.
const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const crypto = require('node:crypto')
const assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..')
const moss = process.argv.includes('--moss')
const shipped = process.argv.includes('--asar')
const bundle = shipped ? path.join(root, 'release-v0.6.15', 'win-unpacked', 'resources', 'app.asar') : root
const out = path.join(root, 'previews', shipped ? moss ? 'campfire-moss-shipped' : 'campfire-shipped' : moss ? 'campfire-moss-integration' : 'campfire-integration')
fs.mkdirSync(out, { recursive: true })
process.env.FOCUSQUEST_QA_USER_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'focusquest-campfire-'))
const report = { checks: [], errors: [], userData: process.env.FOCUSQUEST_QA_USER_DATA, bundle }
if (shipped) {
  const hash = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')
  for (const file of ['out/main/index.js', 'out/preload/index.js', 'out/renderer/index.html']) {
    assert.equal(hash(path.join(bundle, file)), hash(path.join(root, file)), `Packaged ${file} differs from verified build`)
  }
  report.checks.push('ASAR main, preload and renderer entry match the verified build')
}
let win
const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
const js = (source) => win.webContents.executeJavaScript(source, true)
async function until(check, label) {
  const deadline = Date.now() + 20000
  while (Date.now() < deadline) { if (await check()) return; await wait(100) }
  throw new Error(`Timeout: ${label}`)
}
async function shot(name) { fs.writeFileSync(path.join(out, `${name}.png`), (await win.webContents.capturePage()).toPNG()) }
require(path.join(bundle, 'out', 'main', 'index.js'))
;(async () => {
  await app.whenReady()
  await until(async () => { win = BrowserWindow.getAllWindows().find((item) => item.webContents.getURL().endsWith('#/')); return win && !win.webContents.isLoading() }, 'main window')
  win.webContents.setBackgroundThrottling(false)
  win.webContents.on('console-message', (_event, level, message) => { if (level >= 2) report.errors.push(message) })
  win.showInactive()
  await until(() => js('Boolean(document.querySelector(".campfire-stage iframe")?.contentWindow?.__campfire)'), 'campfire scene')
  await wait(600)
  await shot('01-journey-start')
  report.checks.push('New journey draws the authored campfire in the real Electron renderer')
  await js('document.querySelector(".campfire-stage iframe").contentWindow.__campfire.setHover("bridge")')
  await wait(1400)
  await shot('02-bridge-hover')
  await js('document.querySelector(".campfire-stage iframe").contentWindow.__campfire.setHover("steps")')
  await wait(1400)
  await shot('03-steps-hover')
  report.checks.push('Both exits have camera/veil/destination reactions')
  let snapshot = await js('window.focusQuest.addListTask({title:"QA 營火出發"})')
  snapshot = await js(`window.focusQuest.startDailyRun(${JSON.stringify(snapshot.taskList.nextTaskId)})`)
  const route = snapshot.expeditionNodes.find((node) => node.areaId === (moss ? 'area-02-moss-station' : 'area-01-cloud-ruins'))
  assert(route)
  await js(`window.focusQuest.selectExpeditionNode(${JSON.stringify(snapshot.todayRun.id)},${JSON.stringify(route.id)})`)
  await until(() => js(`document.querySelector('.la-route[aria-pressed="true"]') !== null`), 'selected route')
  await shot('04-selected-route')
  await js('document.querySelector(".campfire-stage iframe").contentWindow.__campfire.setStage(1,false)')
  await js('document.querySelector(".campfire-stage iframe").contentWindow.__campfire.playReturn()')
  await wait(4200)
  await shot('05-returned')
  report.checks.push('Returned scene plays the four-second arrival and stage-one trace')
  await js('document.querySelector(".campfire-stage iframe").contentWindow.__campfire.depart()')
  await js('document.querySelector(".campfire-stage iframe").contentWindow.__campfire.advance(0.5)')
  await shot('05a-step-off-log')
  await js('document.querySelector(".campfire-stage iframe").contentWindow.__campfire.advance(0.5)')
  await shot('05b-clear-of-log')
  snapshot = await js(`window.focusQuest.startListFocus({taskId:${JSON.stringify(snapshot.taskList.nextTaskId)}, minimumMinutes:5, blockedProcessNames:[], runId:${JSON.stringify(snapshot.todayRun.id)}, nodeId:${JSON.stringify(route.id)}, plannedMinutes:50})`)
  assert(snapshot.activeSession)
  await until(() => js('Boolean(document.querySelector(".focus-active .campfire-stage iframe")?.contentWindow?.__campfire)'), 'departure scene')
  await wait(Math.max(0, Date.parse(snapshot.activeSession.startedAt) + 2700 - Date.now()))
  await shot('06-borrow-fire')
  await wait(Math.max(0, Date.parse(snapshot.activeSession.startedAt) + 4900 - Date.now()))
  await shot('07-end-of-mist')
  await wait(550)
  await shot('08-handoff')
  await wait(1800)
  await shot('09-map-entry')
  assert(await js('Boolean(document.querySelector(".focus-active canvas"))'))
  report.checks.push('Focus session is persisted immediately; borrow-fire scene gives way to destination after five seconds')
  assert.equal(report.errors.length, 0, report.errors.join('\n'))
  fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report, null, 2))
  app.exit(0)
})().catch((error) => {
  report.errors.push(error.stack || String(error))
  fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report, null, 2))
  console.error(error)
  app.exit(1)
})
