const originalShow = BrowserWindow.prototype.show
BrowserWindow.prototype.show = function () {
  if (this.getTitle() === 'Focus Quest') {
    const primary = screen.getPrimaryDisplay()
    const secondary = screen.getAllDisplays().find((display) => display.id !== primary.id)
    if (secondary) {
      const area = secondary.workArea, bounds = this.getBounds()
      const width = Math.min(bounds.width, area.width), height = Math.min(bounds.height, area.height)
      this.setBounds({ x: area.x + Math.max(0, Math.floor((area.width - width) / 2)), y: area.y + Math.max(0, Math.floor((area.height - height) / 2)), width, height })
      report.checks.push('QA window opened on secondary display')
    } else report.checks.push('No secondary display available; QA window used primary display')
  }
  return originalShow.call(this)
}
